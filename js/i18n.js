async function translateText(text,targetLang){
  if(!text||targetLang==='zh')return text
  const langMap={en:'en',ja:'ja',ko:'ko',tw:'zh-TW'}
  const target=langMap[targetLang]||'en'
  try{
    const res=await fetch('/api/translate',{
      method:'POST',
      headers:{'Content-Type':'application/json'},
      body:JSON.stringify({text:text.substring(0,500),target})
    })
    const data=await res.json()
    if(data.text)return data.text
    return text
  }catch(e){
    try{
      const url=`https://api.mymemory.translated.net/get?q=${encodeURIComponent(text.substring(0,500))}&langpair=zh|${target}`
      const res=await fetch(url)
      const data=await res.json()
      if(data.responseStatus===200&&data.responseData.translatedText){
        return data.responseData.translatedText
      }
      return text
    }catch(e2){
      return text
    }
  }
}

const _transCache={}
async function getCachedTranslation(text,lang){
  if(!text||lang==='zh')return text
  const key=lang+':'+text.substring(0,80)
  if(_transCache[key])return _transCache[key]
  const result=await translateText(text,lang)
  _transCache[key]=result
  return result
}

