const LANG_KEY='lang'

function getLang(){
  const url=new URL(window.location.href)
  const urlLang=url.searchParams.get('lang')
  if(urlLang&&I18N[urlLang]){
    localStorage.setItem(LANG_KEY,urlLang)
    url.searchParams.delete('lang')
    history.replaceState(null,'',url.toString())
    return urlLang
  }
  return localStorage.getItem(LANG_KEY)||'zh'
}

function setLang(lang){
  localStorage.setItem(LANG_KEY,lang)
  window.location.search='?lang='+lang
}

const CURRENCY_CONFIG={
  zh:{symbol:'¥',code:'CNY',name:'人民币'},
  en:{symbol:'$',code:'USD',name:'US Dollar'},
  ja:{symbol:'¥',code:'JPY',name:'日本円'},
  ko:{symbol:'₩',code:'KRW',name:'원'},
  tw:{symbol:'NT$',code:'TWD',name:'新台幣'}
}

const DEFAULT_RATES={USD:1,CNY:7.24,JPY:149.5,KRW:1320,TWD:31.5}

let _rates=null

async function fetchRates(){
  try{
    const res=await fetch('https://api.exchangerate-api.com/v4/latest/USD')
    const data=await res.json()
    _rates=data.rates
    localStorage.setItem('exchangeRates',JSON.stringify(_rates))
    localStorage.setItem('exchangeRatesTime',Date.now().toString())
  }catch(e){
    const saved=localStorage.getItem('exchangeRates')
    if(saved)_rates=JSON.parse(saved)
    else _rates=DEFAULT_RATES
  }
}

function getRates(){
  if(_rates)return _rates
  const saved=localStorage.getItem('exchangeRates')
  if(saved){
    const time=parseInt(localStorage.getItem('exchangeRatesTime')||'0')
    if(Date.now()-time<3600000){
      _rates=JSON.parse(saved)
      return _rates
    }
  }
  _rates=DEFAULT_RATES
  return _rates
}

function convertPrice(usdPrice,targetLang){
  const cfg=CURRENCY_CONFIG[targetLang]||CURRENCY_CONFIG.en
  const rates=getRates()
  const rate=rates[cfg.code]||1
  const converted=parseFloat(usdPrice)*rate
  if(cfg.code==='JPY'||cfg.code==='KRW')return cfg.symbol+Math.round(converted)
  return cfg.symbol+converted.toFixed(2)
}

function getCurrencyCode(){return(CURRENCY_CONFIG[getLang()]||CURRENCY_CONFIG.en).code}
function getCurrencySymbol(){return(CURRENCY_CONFIG[getLang()]||CURRENCY_CONFIG.en).symbol}

function t(key){
  const lang=getLang()
  return(I18N[lang]&&I18N[lang][key])||(I18N.zh[key])||key
}

function applyLang(lang){
  if(!lang)lang=getLang()
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key=el.getAttribute('data-i18n')
    const val=t(key)
    if(el.tagName==='INPUT'&&el.type!=='radio')el.placeholder=val
    else el.innerHTML=val
  })
  document.querySelectorAll('[data-i18n-title]').forEach(el=>{
    el.title=t(el.getAttribute('data-i18n-title'))
  })
  document.documentElement.lang=lang==='tw'?'zh-TW':lang==='zh'?'zh-CN':lang
}

function createLangSwitcher(){
  const current=getLang()
  const langs=[{k:'zh',f:'🇨🇳'},{k:'en',f:'🇺🇸'},{k:'ja',f:'🇯🇵'},{k:'ko',f:'🇰🇷'},{k:'tw',f:'🇹🇼'}]
  const wrap=document.createElement('div')
  wrap.style.cssText='position:relative;display:inline-block'
  const btn=document.createElement('button')
  btn.style.cssText='display:flex;align-items:center;gap:4px;padding:4px 10px;border-radius:6px;background:rgba(255,255,255,.1);color:#fff;border:none;font-size:13px;cursor:pointer'
  btn.innerHTML=langs.find(l=>l.k===current).f+' ▾'
  btn.onclick=e=>{e.stopPropagation();dd.style.display=dd.style.display==='block'?'none':'block'}
  const dd=document.createElement('div')
  dd.style.cssText='display:none;position:absolute;top:100%;right:0;margin-top:4px;background:#fff;border-radius:8px;box-shadow:0 4px 16px rgba(0,0,0,.15);overflow:hidden;z-index:999;min-width:140px'
  langs.forEach(l=>{
    const opt=document.createElement('div')
    opt.style.cssText=`display:flex;align-items:center;gap:8px;padding:10px 14px;font-size:13px;color:#333;cursor:pointer;transition:background .15s${l.k===current?';background:#f0f7ff':''}`
    opt.innerHTML=`<span style="font-size:18px">${l.f}</span><span>${I18N[l.k].name}</span>`
    opt.onmouseover=()=>opt.style.background='#f5f5f5'
    opt.onmouseout=()=>opt.style.background=l.k===current?'#f0f7ff':''
    opt.onclick=()=>{setLang(l.k);dd.style.display='none';btn.innerHTML=l.f+' ▾';dd.querySelectorAll('div').forEach(d=>d.style.background='');opt.style.background='#f0f7ff'}
    dd.appendChild(opt)
  })
  document.addEventListener('click',()=>dd.style.display='none')
  wrap.appendChild(btn)
  wrap.appendChild(dd)
  return wrap
}

async function detectLangByIP(){
  const url=new URL(window.location.href)
  if(url.searchParams.has('lang'))return
  if(localStorage.getItem(LANG_KEY))return
  try{
    const res=await fetch('https://ipapi.co/json/')
    const data=await res.json()
    const cc=data.country_code
    const map={'CN':'zh','TW':'tw','HK':'tw','JP':'ja','KR':'ko'}
    const lang=map[cc]||'en'
    localStorage.setItem(LANG_KEY,lang)
  }catch(e){
    localStorage.setItem(LANG_KEY,'zh')
  }
}

function initI18n(){
  detectLangByIP().then(()=>{
    applyLang()
    fetchRates()
    const nav=document.querySelector('.header-right')
    if(nav)nav.prepend(createLangSwitcher())
  })
}

